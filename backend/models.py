ConnectionRequestStatus = Literal["PENDING", "ACCEPTED", "REJECTED"]


class ConnectionRequestCreate(BaseModel):
    """Payload to send a connection request to another student."""
    sender_id:   int = Field(..., description="Student profile ID sending the request")
    receiver_id: int = Field(..., description="Target student profile ID")
    message:     Optional[str] = Field("", max_length=250, description="Optional intro note")


class ConnectionRequestAction(BaseModel):
    """Action payload to accept or reject an incoming request."""
    action:     Literal["ACCEPT", "REJECT"] = Field(..., description="ACCEPT or REJECT")
    profile_id: int                         = Field(..., description="Profile ID performing action (must be receiver)")


class ConnectionRequestOut(BaseModel):
    """Output for a connection request record."""
    id:          int
    sender_id:   int
    receiver_id: int
    status:      str
    message:     str
    created_at:  str
    updated_at:  str
    sender:      Optional[StudentProfileOut] = None
    receiver:    Optional[StudentProfileOut] = None

    model_config = {"from_attributes": True}


class ConnectionOut(BaseModel):
    """Output for an established two-way connection."""
    connection_id:   int
    peer_profile:    StudentProfileOut
    connected_since: str


class PeerMessageCreate(BaseModel):
    """Payload to send a message to a connected peer."""
    sender_id: int = Field(..., description="Student profile ID sending the message")
    content:   str = Field(..., min_length=1, max_length=1000, description="Chat message text")


class PeerMessageOut(BaseModel):
    """Output representation of a peer-to-peer message."""
    id:            int
    connection_id: int
    sender_id:     int
    receiver_id:   int
    content:       str
    is_read:       bool = False
    created_at:    str


