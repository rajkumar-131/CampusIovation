"""
models.py — Defines data shapes using Pydantic.

What is Pydantic?
  A Python library that checks incoming data automatically.
  If someone sends invalid or malformed data, FastAPI + Pydantic
  rejects it with a clear error message before reaching the database.
"""

from pydantic import BaseModel, Field, field_validator
from typing import Optional, Literal
import json


# ── Allowed categories & priorities (GreenCampus AI Tickets) ──────────────────
AICategoryType = Literal[
    "Water & Plumbing",
    "Electrical",
    "Cleanliness",
    "Infrastructure",
    "Sustainability",
    "Other",
]

CategoryType = Literal[
    "Water & Plumbing",
    "Electrical",
    "Cleanliness",
    "Infrastructure",
    "Sustainability",
    "Internet & IT",
    "Safety & Security",
    "Other",
]

PriorityType = Literal["High", "Medium", "Low"]
StatusType   = Literal["Open", "In Progress", "Resolved"]


# ── Model for Gemini AI structured output ────────────────────────────────────
class GeminiClassification(BaseModel):
    """Structured JSON output generated by Gemini (or the fallback classifier)."""
    category: AICategoryType = Field(
        ...,
        description="Categorised campus issue area"
    )
    priority: PriorityType = Field(
        ...,
        description="Urgency and risk assessment: High, Medium, or Low"
    )
    department: str = Field(
        ...,
        min_length=2,
        max_length=120,
        description="Responsible campus department or team"
    )
    explanation: str = Field(
        ...,
        min_length=5,
        max_length=1000,
        description="Reasoning behind category, priority, and risk assessment"
    )
    recommended_action: str = Field(
        ...,
        min_length=5,
        max_length=1000,
        description="Recommended next steps for campus maintenance staff (not resolved)"
    )
    source: Literal["gemini", "grok", "openai", "fallback"] = Field(
        "gemini",
        description="Origin of the classification: 'gemini', 'grok', 'openai', or 'fallback'"
    )


# ── Request model for on-demand AI classification ─────────────────────────────
class AIClassifyRequest(BaseModel):
    title: str = Field(..., min_length=5, max_length=120, description="Short issue title")
    description: str = Field(..., min_length=15, max_length=2000, description="Issue description")
    location: str = Field(..., min_length=3, max_length=200, description="Campus location")
    category: Optional[str] = Field("Other", description="User-reported category if any")


# ── Model for creating a new ticket (POST /api/tickets) ───────────────────────
class TicketCreate(BaseModel):
    title:        str          = Field(..., min_length=5,  max_length=120,  description="Short issue title")
    description:  str          = Field(..., min_length=20, max_length=2000, description="Detailed description of the issue")
    category:     CategoryType = Field(..., description="Type of issue")
    location:     str          = Field(..., min_length=3,  max_length=200,  description="Where on campus")
    submitted_by: str          = Field("Anonymous", max_length=100, description="Reporter's name")

    # Optional overrides (if omitted, AI fills these in automatically)
    department:    Optional[str]          = Field("Unassigned", max_length=100)
    priority:      Optional[PriorityType] = Field("Medium")
    ai_suggestion: Optional[str]          = Field(None, max_length=1000)


# ── Model for updating ticket status (PATCH /api/tickets/{id}/status) ─────────
class TicketStatusUpdate(BaseModel):
    status: StatusType = Field(..., description="New status for the ticket")


# ── Model for reading/returning a ticket (all GET responses) ──────────────────
class TicketOut(BaseModel):
    id:             int
