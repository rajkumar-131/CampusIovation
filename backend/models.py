ActivityType = Literal["STUDY", "COFFEE", "LUNCH", "WALK", "CASUAL_CHAT"]
DurationMinutesType = Literal[15, 30, 60]

PREDEFINED_CAMPUS_AREAS = [
    "Central Library",
    "Main Cafeteria",
    "Student Activity Center (SAC)",
    "Science & Engineering Quad",
    "Hostel Common Room",
    "Sports Complex & Ground",
    "Green Lawn / Campus Park",
    "Anywhere on Campus",
]


class StudentProfileCreate(BaseModel):
    """Schema to create a student profile."""
    name:       str       = Field(..., min_length=2, max_length=80, description="Student's display name")
    department: str       = Field(..., min_length=2, max_length=100, description="Department / Major")
    study_year: str       = Field(..., min_length=2, max_length=50, description="Study Year (e.g. 1st Year, 2nd Year, etc.)")
    bio:        Optional[str] = Field("", max_length=300, description="Short intro or bio")
    interests:  list[str] = Field(default_factory=list, description="List of student interests")

    @field_validator("name", "department", "study_year")
    @classmethod
    def strip_whitespace(cls, v: str) -> str:
        cleaned = v.strip()
        if not cleaned:
            raise ValueError("Field cannot be empty or whitespace only")
        return cleaned


class StudentProfileOut(BaseModel):
    """Schema returned when reading a student profile."""
    id:         int
    name:       str
    department: str
    study_year: str
    bio:        str
    interests:  list[str]
    created_at: str

    model_config = {"from_attributes": True}


class AvailabilityCreate(BaseModel):
    """Schema for a student to broadcast their current availability."""
    profile_id:       int                 = Field(..., description="ID of the student's profile")
    activity:         ActivityType        = Field(..., description="STUDY, COFFEE, LUNCH, WALK, or CASUAL_CHAT")
    duration_minutes: DurationMinutesType = Field(..., description="Availability window: 15, 30, or 60 minutes")
    location_area:    Optional[str]       = Field("Anywhere on Campus", description="General campus area (non-GPS)")
    note:             Optional[str]       = Field("", max_length=200, description="Optional brief status message")

    @field_validator("location_area")
    @classmethod
    def validate_location_area(cls, v: Optional[str]) -> str:
        if not v or not v.strip():
            return "Anywhere on Campus"
        return v.strip()


class ActiveAvailabilityOut(BaseModel):
    """Schema for an active availability record."""
    id:                int
    profile_id:        int
    activity:          ActivityType
    duration_minutes:  int
    location_area:     str
    note:              str
    available_from:    str
    expires_at:        str
    minutes_remaining: int
    status:            str

    model_config = {"from_attributes": True}


class ActiveStudentOut(BaseModel):
    """Combined view of student profile + live availability for the directory."""
    availability_id:   int
    profile_id:        int
    name:              str
    department:        str
    study_year:        str
    bio:               str
